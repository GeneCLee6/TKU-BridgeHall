// Writes src/content/manifest.ts: every bundled convention without its content (ARCHITECTURE.md §4).
// Run with `npm run manifest` after adding or changing a convention; a content test fails while
// the manifest is out of date.
import { writeFileSync } from 'node:fs'
import { conventions } from '../src/content/index.ts'
import { conventionMeta } from '../src/lib/sections.ts'

const target = new URL('../src/content/manifest.ts', import.meta.url)
const body = JSON.stringify(conventions.map(conventionMeta), null, 2)
writeFileSync(
  target,
  `// Generated by scripts/build-manifest.ts (npm run manifest). Do not edit by hand.
import type { ConventionMeta } from '../types/convention.ts'

export const manifest: ConventionMeta[] = ${body}
`,
)
console.log(`manifest: ${conventions.length} conventions`)
