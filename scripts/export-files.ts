// Turns GET /api/book/export into the backup's files (L1, e8-t12; CONTENT_GUIDE.md §6.5). Kept apart
// from scripts/export-content.ts so tests/content/export.test.ts can check it without the Worker.
//
// The files mirror this repository's layout, so a backup drops straight into src/content (to run the
// content tests on it, or to take an online version back into the built-in layer):
//
//   src/content/conventions/<slug>.ts   one per convention members read (hidden ones left out)
//   src/content/index.ts                the registry, in catalogue order
//   src/content/categories.ts           only when the categories were edited online
//   export.json                         the export itself, without its time (so an unchanged
//                                       export changes no file)
//   README.md                           what is in the backup: each convention's layer and version
import type { BookExport, ExportedOnline } from '../src/lib/bookExport.ts'

/** The registry's name for a convention: its slug in camelCase (jacoby-2nt -> jacoby2nt) */
export function exportName(slug: string): string {
  const [first, ...rest] = slug.split('-').filter(Boolean)
  const name = first + rest.map((part) => part[0].toUpperCase() + part.slice(1)).join('')
  return /^[a-z_$]/i.test(name) ? name : `c${name}`
}

const GENERATED = 'Generated by scripts/export-content.ts from GET /api/book/export; do not edit by hand.'

const day = (ms: number) => new Date(ms).toISOString().slice(0, 10)
const onlineNote = (online: ExportedOnline) => `online version ${online.version} (${online.updatedBy}, ${day(online.updatedAt)})`

/** Every file of the backup by its path, in a stable order */
export function exportFiles(data: BookExport): Map<string, string> {
  if (data.format !== 1) throw new Error(`Unknown export format ${String(data.format)}: update scripts/export-files.ts`)
  const files = new Map<string, string>()
  const names = new Map<string, string>()

  for (const item of data.conventions) {
    const name = exportName(item.slug)
    if ([...names.values()].includes(name)) throw new Error(`Two conventions would both be called ${name}`)
    names.set(item.slug, name)
    const layer = item.source === 'online' && item.online
      ? `${item.builtin ? 'An online version over the built-in convention' : 'Online only'}: ${onlineNote(item.online)}.`
      : 'The built-in layer.'
    files.set(
      `src/content/conventions/${item.slug}.ts`,
      [
        `// ${GENERATED}`,
        `// ${layer}`,
        "import type { Convention } from '../../types/convention.ts'",
        '',
        `export const ${name}: Convention = ${JSON.stringify(item.convention, null, 2)}`,
        '',
      ].join('\n'),
    )
  }

  files.set(
    'src/content/index.ts',
    [
      `// ${GENERATED}`,
      "import type { Convention } from '../types/convention.ts'",
      ...data.conventions.map((c) => `import { ${names.get(c.slug)} } from './conventions/${c.slug}.ts'`),
      '',
      '/** Every convention members read at the export, in catalogue order */',
      'export const conventions: Convention[] = [',
      ...data.conventions.map((c) => `  ${names.get(c.slug)},`),
      ']',
      '',
      'export const conventionBySlug = (slug: string): Convention | undefined =>',
      '  conventions.find((c) => c.slug === slug)',
      '',
      "export { categories } from './categories.ts'",
      "export { references } from './references.ts'",
      '',
    ].join('\n'),
  )

  if (data.categories.length) {
    const categories = [...data.categories].sort((a, b) => a.order - b.order)
    files.set(
      'src/content/categories.ts',
      [
        `// ${GENERATED} The categories as edited online.`,
        "import type { Category } from '../types/convention.ts'",
        '',
        `export const categories: Category[] = ${JSON.stringify(categories, null, 2)}`,
        '',
      ].join('\n'),
    )
  }

  const { exportedAt: _time, ...stable } = data
  files.set('export.json', `${JSON.stringify(stable, null, 2)}\n`)
  files.set('README.md', readme(data))
  return files
}

function readme(data: BookExport): string {
  const row = (cells: string[]) => `| ${cells.join(' | ')} |`
  const lines = [
    '# TKU BridgeHall content backup',
    '',
    `${GENERATED} Every convention members read, the online versions laid over the built-in layer`,
    `(online version ${data.version}, built-in version ${data.builtinVersion}). Drafts are not included.`,
    '',
    row(['slug', 'name', 'layer', 'online version']),
    row(['---', '---', '---', '---']),
    ...data.conventions.map((c) =>
      row([
        `\`${c.slug}\``,
        c.convention.nameZh,
        c.source === 'builtin' ? 'built-in' : c.builtin ? 'online over built-in' : 'online only',
        c.online ? onlineNote(c.online) : '',
      ]),
    ),
    '',
  ]
  if (data.hidden.length) {
    lines.push('Hidden online (not in src/content):', '')
    for (const h of data.hidden) lines.push(`- \`${h.slug}\`${h.builtin ? ' (built-in)' : ''}: ${onlineNote(h.online)}`)
    lines.push('')
  }
  lines.push(data.categories.length ? 'The categories were edited online: src/content/categories.ts.' : 'The categories were never edited online: BridgeHall\'s own src/content/categories.ts applies.', '')
  return lines.join('\n')
}

/** A summary that names no convention text, for public logs */
export function exportSummary(data: BookExport): string {
  const online = data.conventions.filter((c) => c.source === 'online')
  return `${data.conventions.length} conventions (${online.length} online, ${online.filter((c) => !c.builtin).length} of them online only), ${data.hidden.length} hidden; online version ${data.version}, built-in version ${data.builtinVersion}`
}
